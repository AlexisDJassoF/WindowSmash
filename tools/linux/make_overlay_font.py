#!/usr/bin/env python3
"""The debug overlay's glyph atlas for the Linux build, written as runtime/linux/overlay_font.h
(kept in the repository, so a build needs neither this nor a font).

Usage: make_overlay_font.py [--font <file.ttf>] [--out <header>]

The Windows build draws its atlas at start-up with GDI in Consolas (runtime/gpu_overlay.c). The
Linux one is drawn here, the same way - printable ASCII, white on black, a 20-pixel bold
monospaced font, one 12x24 cell each, 16 cells to a row, one pixel down from the cell's top - but
in DejaVu Sans Mono Bold, a free font, so the header can be kept in the repository. The coverage
is the drawing's grey level, 0 to 255. Needs Pillow (with FreeType) and the font: Debian and
Ubuntu's fonts-dejavu-mono (or fonts-dejavu-core) has it at the default path. tools/linux/
make_overlay_font.c is the older way, which drew the header with GDI on Windows."""
import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
OUT = os.path.join(REPO, "runtime", "linux", "overlay_font.h")
# (as runtime/gpu_overlay.c)
CELL_W, CELL_H, COLS = 12, 24, 16
ATLAS_W, ATLAS_H = CELL_W * COLS, CELL_H * 6
SIZE = 20   # pixels to the em: GDI's CreateFontW(-20, ...)


def draw(font_path):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(font_path, SIZE)
    atlas = Image.new("L", (ATLAS_W, ATLAS_H), 0)
    pen = ImageDraw.Draw(atlas)
    for c in range(32, 127):
        x, y = (c - 32) % COLS * CELL_W, (c - 32) // COLS * CELL_H + 1
        pen.text((x, y), chr(c), fill=255, font=font, anchor="la")   # (left, at the ascender: GDI's TA_TOP)
    return atlas.tobytes()


def header(coverage, font_path):
    with open(font_path, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    lines = [f"/* Generated by tools/linux/make_overlay_font.py: {ATLAS_W}x{ATLAS_H} coverage, printable ASCII in "
             f"{CELL_W}x{CELL_H} cells,\n * {os.path.basename(font_path)} at {SIZE} px (sha256 {digest[:16]}...). */",
             f"static const unsigned char overlay_font[{ATLAS_W * ATLAS_H}] = {{"]
    for i in range(0, len(coverage), 32):
        lines.append("".join(f"{v}," for v in coverage[i:i + 32]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Write the Linux debug overlay's glyph atlas (runtime/linux/overlay_font.h).")
    ap.add_argument("--font", default=FONT, help=f"the font (default: {FONT})")
    ap.add_argument("--out", default=OUT, help="the header to write (default: runtime/linux/overlay_font.h)")
    a = ap.parse_args()
    if not os.path.isfile(a.font):
        raise SystemExit(f"{a.font}: not there (sudo apt install fonts-dejavu-mono, or name another with --font)")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(header(draw(a.font), a.font))
    print(f"{a.out}: {ATLAS_W}x{ATLAS_H} from {a.font}")


if __name__ == "__main__":
    main()
