#!/usr/bin/env python3
"""Install a game version into a folder of its own and build it, with one command.

Usage:
  install_version.py install --tree <dir> [--update <nsp>] [--dlc <dir>] [--base <romfs.cfg>]
                             [--keys <dir>] [--jobs N] [--no-build] [--redo <step>[,<step>...]] [--force]
  install_version.py describe --tree <dir> [--update <nsp>] [--keys <dir>]
  install_version.py list

install  fills <tree>, a folder laid out like the port's own (dump/, build/, save/), and builds it:
  exefs    dump/exefs: the update's program, or without --update the base's (its NCA's ExeFS)
  romfs    dump/modules/romfs.cfg: the update applied over the base (tools/update.py: layered, with
           romfs.layers and romfs_patch.bin), or without --update the base's own romfs.cfg
  aoc      dump/modules/aoc.cfg: the add-on content (DLC) packages in --dlc (tools/nca.py aoc-cfg)
  nro      dump/nro: every fighter module in data.arc (tools/arc.py nro)
  extras   dump/fonts and dump/shadercache copied from the port's own dump/, and save/ from the
           port's save/ - each only when the tree has none: the tree's save is its own from then on
  version  version.txt (below)
  build    build/ssbu.exe: tools/recomp.py all --tree, which first lists imports nothing provides,
           and reuses what another tree built for a module with the same build id (modcache.py);
           on macOS build-mac/WindowSmash.app: the C generated by recomp.py all --generate-only,
           then compiled by tools/mac/build_mac.py --port <tree>
  A step whose inputs are those of last time (<tree>/install.json) and whose result is there is
  skipped; --redo names steps to do again anyway. A folder made before this tool (a dump/ but no
  install.json, e.g. v13.0.5) is refused unless --force, and the port's own folder always is.
describe writes version.txt for a tree, also one made before this tool or the port's own folder.
list     the trees and what each holds.

version.txt: the version first (the display version from the control data, e.g. 13.0.5, or
data.arc's when there is no control data), then "main <build id>", "data.arc <version>", and
the update's title version. The launchers (tools/pick_version.bat) show its first line.

Defaults: --base <port>/dump/modules/romfs.cfg (the installed game), --keys the SSBU_KEYS
environment variable, --jobs 20. Run from anywhere; a relative --tree is taken from the current
folder. Examples:
  python tools/install_version.py install --tree v13.0.5 --update "D:\\MyDump\\update.nsp" --dlc "D:\\MyDump\\dlc" --keys "D:\\MyKeys"
  python tools/install_version.py install --tree v11.0.0 --dlc "D:\\MyDump\\dlc" --keys "D:\\MyKeys"
"""
import argparse
import json
import os
import shutil
import struct
import subprocess
import sys
import time

TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)
import modcache  # noqa: E402
import update  # noqa: E402
from arc import Arc, extract_nros  # noqa: E402
from nca import Nca, RomfsImage, aoc_cfg, copy_out, nsp_ncas, pfs0_entries, romfs_entries  # noqa: E402
from nso import Module  # noqa: E402

ROOT = modcache.ROOT
STEPS = ("exefs", "romfs", "aoc", "nro", "extras", "version", "build")
MACOS = sys.platform == "darwin"   # (built by tools/mac/build_mac.py, into the tree's build-mac/)


def program(tree):
    """The game program a tree's build makes."""
    if MACOS:
        return os.path.join(tree, "build-mac", "WindowSmash.app", "Contents", "MacOS", "ssbu")
    return os.path.join(tree, "build", "ssbu.exe")


def log(msg):
    print(msg, flush=True)


def plain_source(cfg):
    """The file a plain romfs.cfg reads the RomFS from (the base NCA)."""
    img = RomfsImage(cfg)
    if img.entries is not None:
        raise SystemExit(f"{cfg} is layered (an update over its base): --base takes the base release's own romfs.cfg")
    return os.path.abspath(img.f.name)


def stamp(path):
    """What identifies an input file: where it is, its size and time."""
    st = os.stat(path)
    return [os.path.abspath(path), st.st_size, int(st.st_mtime)]


def folder_stamp(path):
    out = []
    for dp, _dirs, files in os.walk(path):
        out += [[os.path.relpath(os.path.join(dp, f), path), os.path.getsize(os.path.join(dp, f))]
                for f in files if f.endswith((".nsp", ".nca"))]
    return sorted(out)


# ---- what version a tree is ---------------------------------------------------------------
def nacp_version(ncas):
    """The display version in the control.nacp of the first Control NCA, or None."""
    for nca in ncas:
        if nca.content_type != 2:
            continue
        try:
            sec = nca.section(0)
            for path, off, _size in romfs_entries(sec):
                if path == "control.nacp":
                    return sec.read(off + 0x3060, 0x10).split(b"\0")[0].decode("utf-8", "replace") or None
        except (SystemExit, struct.error, ValueError, NotImplementedError):
            continue
    return None


def installed_controls(nca_path, keys, title_id):
    """The Control NCAs installed next to a program NCA (the same title's)."""
    folder = os.path.dirname(nca_path)
    for f in sorted(os.listdir(folder)):
        p = os.path.join(folder, f)
        if f.endswith(".nca") and not f.endswith(".cnmt.nca") and os.path.isfile(p):
            try:
                nca = Nca(p, keys)
            except (SystemExit, OSError, ValueError):
                continue
            if nca.content_type == 2 and nca.title_id == title_id:
                yield nca


def update_meta(nsp, keys):
    """(title id, title version) of an update NSP, from its content metadata."""
    for _name, nca in nsp_ncas(nsp, keys, ".cnmt.nca"):
        sec = nca.section(1)
        for n, off, _size in pfs0_entries(sec):
            if n.endswith(".cnmt"):
                title, version = struct.unpack_from("<QI", sec.read(off, 0x10))
                return title, version
    return None, None


def arc_version(v):
    return f"{v >> 16}.{(v >> 8) & 0xFF}.{v & 0xFF}"


def describe(tree, keys, nsp=None, base_cfg=None):
    """Write <tree>/version.txt; returns its first line."""
    modules = os.path.join(tree, "dump", "modules")
    main = Module(os.path.join(tree, "dump", "exefs", "main"))
    data = arc_version(Arc(os.path.join(modules, "romfs.cfg")).version)
    lines, display = [f"main {main.build_id}", f"data.arc {data}"], None
    if nsp:
        title, version = update_meta(nsp, keys)
        display = nacp_version(nca for _n, nca in nsp_ncas(nsp, keys))
        lines.append(f"update {title or 0:016X} v{version} {os.path.basename(nsp)}")
    else:
        try:
            source = plain_source(base_cfg or os.path.join(modules, "romfs.cfg"))
            program = Nca(source, keys)
            display = nacp_version(installed_controls(source, keys, program.title_id))
            lines.append(f"base {program.title_id:016X} {os.path.basename(source)}")
        except SystemExit:   # a layered tree made before this tool: no update to read
            pass
    if display and display != data:
        lines.append(f"(the control data says {display}; the game's data says {data})")
    first = display or data
    text =(f"{first}\n# game version of this folder (tools/install_version.py describe): the version, then what it is made of\n"
            + "\n".join(lines) + "\n")
    with open(os.path.join(tree, "version.txt"), "w", newline="\n") as f:
        f.write(text)
    log(f"version: {first} (main {main.build_id[:16]}, data.arc {data}) -> {os.path.join(tree, 'version.txt')}")
    return first


# ---- install ------------------------------------------------------------------------------
def install(a):
    t0 = time.time()
    tree = os.path.abspath(a.tree)
    if modcache.same_path(tree, ROOT):
        raise SystemExit("the port's own folder holds the installed base as it is: install into a folder of its own (e.g. --tree v13.0.5)")
    state_path = os.path.join(tree, "install.json")
    if os.path.isdir(os.path.join(tree, "dump")) and not os.path.exists(state_path) and not a.force:
        raise SystemExit(f"{tree} was made before install_version.py (it has a dump/ but no install.json): "
                         "pick another folder, or --force to install over it")
    state = json.load(open(state_path)) if os.path.exists(state_path) else {}
    redo = {s for s in (a.redo or "").split(",") if s}
    if redo - set(STEPS):
        raise SystemExit(f"--redo takes {', '.join(STEPS)}")
    base_cfg = os.path.abspath(a.base)
    base_nca = plain_source(base_cfg)
    keys = a.keys
    dump, modules = os.path.join(tree, "dump"), os.path.join(tree, "dump", "modules")
    os.makedirs(modules, exist_ok=True)
    nsp = os.path.abspath(a.update) if a.update else None
    patch = None
    log(f"installing {'the update ' + os.path.basename(nsp) if nsp else 'the base'} into {tree}")

    def due(step, inputs, there):
        if step in redo or state.get(step) != inputs or not there:
            log(f"[{step}]")
            return True
        log(f"[{step}] up to date")
        return False

    def done(step, inputs):
        state[step] = inputs
        with open(state_path, "w", newline="\n") as f:
            json.dump(state, f, indent=1)

    def the_patch():
        nonlocal patch
        patch = patch or update.open_patch(nsp, keys)
        return patch

    inputs = {"update": stamp(nsp) if nsp else None, "base": stamp(base_nca)}
    if due("exefs", inputs, os.path.exists(os.path.join(dump, "exefs", "main"))):
        if nsp:
            update.apply_exefs(the_patch(), tree)
        else:
            sec = Nca(base_nca, keys).section(1)
            for name, off, size in pfs0_entries(sec):
                log(f"  {name:<12} {size:>10}")
                copy_out(sec, off, size, os.path.join(dump, "exefs", name))
        done("exefs", inputs)

    cfg = os.path.join(modules, "romfs.cfg")
    inputs = {"update": stamp(nsp) if nsp else None, "base": open(base_cfg, encoding="utf-8-sig").read()}
    romfs_changed = due("romfs", inputs, os.path.exists(cfg))
    if romfs_changed:
        if nsp:
            update.apply_romfs(the_patch(), base_cfg, keys, tree)
        else:
            for n in ("romfs.layers", "romfs_patch.bin", "romfs.unverified.txt"):   # an update applied before
                if os.path.exists(os.path.join(modules, n)):
                    os.remove(os.path.join(modules, n))
            shutil.copyfile(base_cfg, cfg)
            log(f"  {cfg}: the base's RomFS, read in place from {base_nca}")
        done("romfs", inputs)

    aoc = os.path.join(modules, "aoc.cfg")
    inputs = {"dlc": [os.path.abspath(a.dlc), folder_stamp(a.dlc)] if a.dlc else None}
    if due("aoc", inputs, os.path.exists(aoc) or not a.dlc):
        if a.dlc:
            aoc_cfg(a.dlc, keys, aoc, Nca(base_nca, keys).title_id)
        elif os.path.exists(aoc):
            os.remove(aoc)
            log("  no DLC: aoc.cfg removed")
        else:
            log("  no DLC")
        done("aoc", inputs)

    nro = os.path.join(dump, "nro")
    log("[nro]")
    if romfs_changed and os.path.isdir(nro):   # another version's modules: placed again from scratch
        shutil.rmtree(nro)
    n = extract_nros(Arc(cfg), nro)
    log(f"  {n} new, {len([f for f in os.listdir(nro) if f.endswith('.nro')])} modules in {nro}")
    done("nro", {})

    log("[extras]")
    for sub in ("fonts", "shadercache"):
        src, dst = os.path.join(ROOT, "dump", sub), os.path.join(dump, sub)
        if os.path.isdir(dst):
            log(f"  dump/{sub}: kept")
        elif os.path.isdir(src):
            shutil.copytree(src, dst)
            log(f"  dump/{sub}: copied from the port's own")
    if os.path.isdir(os.path.join(tree, "save")):
        log("  save: kept (this version's own)")
    elif os.path.isdir(os.path.join(ROOT, "save")):
        shutil.copytree(os.path.join(ROOT, "save"), os.path.join(tree, "save"))
        log("  save: a copy of the port's save/ (the game upgrades it on its first boot)")
    done("extras", {})

    log("[version]")
    describe(tree, keys, nsp, base_cfg)
    done("version", {})

    if a.no_build:
        log(f"done in {time.time() - t0:.0f}s (not built: --no-build)")
        return
    log("[build]")
    cmd = [sys.executable, os.path.join(TOOLS, "recomp.py"), "all", os.path.join(dump, "exefs"),
           "--out", os.path.join(tree, "build"), "--tree", tree, "--jobs", str(a.jobs)]
    cmds = [cmd]
    if MACOS:   # (the C only, then compiled and linked for macOS)
        cmds = [cmd + ["--generate-only"],
                [sys.executable, os.path.join(TOOLS, "mac", "build_mac.py"), "--port", tree, "--jobs", str(a.jobs)]]
    for c in cmds:
        r = subprocess.run(c)
        if r.returncode:
            raise SystemExit(f"the build failed (exit {r.returncode}); run again to go on from where it stopped")
    done("build", {})
    launcher = "Play SSBU.command" if MACOS else "Play SSBU.bat"
    log(f"done in {time.time() - t0:.0f}s: {program(tree)} - start it with {launcher}")


def list_trees():
    for t in modcache.trees():
        vt = os.path.join(t, "version.txt")
        ver = open(vt).readline().strip() if os.path.exists(vt) else "?"
        exe = program(t)
        built = time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(exe))) if os.path.exists(exe) else "not built"
        name = "(the port's own folder)" if modcache.same_path(t, ROOT) else os.path.basename(t)
        log(f"  {ver:<10} {name:<28} {built}")


def main():
    ap = argparse.ArgumentParser(description="Install a game version into a folder of its own and build it.")
    ap.add_argument("cmd", choices=["install", "describe", "list"])
    ap.add_argument("--tree", help="the version's folder, e.g. v13.0.5")
    ap.add_argument("--update", help="the update (a Patch NSP); without it, the base itself")
    ap.add_argument("--dlc", help="a folder of DLC packages (.nsp, or installed .nca)")
    ap.add_argument("--base", default=os.path.join(ROOT, "dump", "modules", "romfs.cfg"),
                    help="the base game's romfs.cfg (default: the port's own)")
    ap.add_argument("--keys", default=os.environ.get("SSBU_KEYS"), help="folder with prod.keys (default: SSBU_KEYS)")
    ap.add_argument("--jobs", type=int, default=20)
    ap.add_argument("--no-build", action="store_true", help="fill the folder, don't build")
    ap.add_argument("--redo", help="steps to do again even if up to date: " + ",".join(STEPS))
    ap.add_argument("--force", action="store_true", help="install over a folder made before this tool")
    a = ap.parse_args()
    if a.cmd == "list":
        return list_trees()
    if not a.tree:
        raise SystemExit(f"{a.cmd} needs --tree <folder>")
    if not a.keys:
        raise SystemExit(f"{a.cmd} needs --keys <folder with prod.keys>, or SSBU_KEYS set to it")
    if a.cmd == "describe":
        return describe(os.path.abspath(a.tree), a.keys, a.update and os.path.abspath(a.update))
    install(a)


if __name__ == "__main__":
    main()
